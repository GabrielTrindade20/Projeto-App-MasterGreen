// Executar: node tests/browser-smoke.cjs [caminho do pacote playwright]
const { chromium } = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'msedge' });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.addInitScript(() => { window.print = () => { window.__printed = true; }; });
    await page.goto('http://127.0.0.1:8081', { waitUntil: 'networkidle' });
    await page.getByLabel('CUSTOS POR m²', { exact: true }).fill('10');
    await page.getByLabel('VALOR POR METRO', { exact: true }).fill('80');
    await page.getByLabel('METRAGEM (m²)', { exact: true }).fill('10');
    await page.getByRole('textbox', { name: 'DESCONTO %', exact: true }).fill('10');
    await page.getByText(/R\$\s*584,00/).waitFor();
    await page.getByText(/R\$\s*720,00/).waitFor();
    await page.getByRole('button', { name: 'Fazer Proposta', exact: true }).click();
    await page.getByRole('button', { name: 'Gerar PDF', exact: true }).click();
    await page.getByText('Preencha o nome do cliente.', { exact: true }).waitFor();
    await page.getByLabel('Cliente', { exact: true }).fill('Cliente <Teste> & Cia');
    await page.getByLabel('A/C', { exact: true }).fill('Contato');
    await page.getByLabel('Telefone', { exact: true }).fill('61999998888');
    assert.equal(await page.getByLabel('Telefone', { exact: true }).inputValue(), '(61) 99999-8888');
    await page.getByLabel('CPF ou CNPJ', { exact: true }).fill('12345678901');
    assert.equal(await page.getByLabel('CPF ou CNPJ', { exact: true }).inputValue(), '123.456.789-01');
    await page.getByLabel('Data da proposta (DD/MM/AAAA)', { exact: true }).fill('11/10/2026');
    await page.getByLabel('Frete incluso?', { exact: true }).selectOption('Incluso');
    await page.getByLabel('Quantidade', { exact: true }).fill('12');
    await page.getByLabel('Entrada %', { exact: true }).fill('50');
    await page.getByRole('button', { name: 'Adicionar Item', exact: true }).click();
    await page.getByLabel('Metragem do item 1 (m²)', { exact: true }).fill('2,5');
    await page.getByLabel('Valor por metro do item 1', { exact: true }).fill('80,50');
    await page.getByLabel('Descrição do produto 1', { exact: true }).fill('Grama sintética');
    await page.getByRole('button', { name: 'Adicionar Item', exact: true }).click();
    await page.getByLabel('Metragem do item 2 (m²)', { exact: true }).fill('2');
    await page.getByLabel('Valor por metro do item 2', { exact: true }).fill('30');
    await page.getByLabel('Descrição do produto 2', { exact: true }).fill('Piso');
    await page.getByRole('textbox', { name: 'DESCONTO %', exact: true }).fill('10');
    await page.getByText(/R\$\s*235,13/).waitFor();
    await page.getByRole('button', { name: 'Remover item 2', exact: true }).click();
    await page.getByText(/R\$\s*181,13/).waitFor();
    await page.getByRole('button', { name: 'Visualizar PDF', exact: true }).click();
    const pdf = page.frameLocator('iframe[title="Proposta MasterGreen"]');
    await pdf.getByText(/Cliente <Teste> & Cia/).waitFor({ state: 'attached' });
    await pdf.getByText(/R\$\s*181,13/).waitFor({ state: 'attached' });
    await pdf.getByText(/50% de entrada \+ 50% na entrega/).waitFor({ state: 'attached' });
    assert.equal(await pdf.locator('script').count(), 0);
    const previewFrame = page.frames().find((frame) => frame.url() === 'about:srcdoc');
    assert.equal(await previewFrame.evaluate(() => window.__printed), true);
    assert.equal(await pdf.locator('img').evaluate((img) => img.complete && img.naturalWidth > 0), true);
    await page.getByRole('tab', { name: /Orçamento/ }).click();
    await page.getByText(/R\$\s*720,00/).waitFor();
    await page.getByRole('button', { name: 'Limpar orçamento', exact: true }).click();
    await page.getByRole('button', { name: 'Continuar preenchendo', exact: true }).click();
    assert.equal(await page.getByLabel('METRAGEM (m²)', { exact: true }).inputValue(), '10');
    await page.getByRole('button', { name: 'Limpar orçamento', exact: true }).click();
    await page.getByRole('button', { name: 'Sim, limpar', exact: true }).click();
    assert.equal(await page.getByLabel('METRAGEM (m²)', { exact: true }).inputValue(), '');
    await page.getByRole('tab', { name: /Proposta/ }).click();
    assert.equal(await page.getByLabel('Cliente', { exact: true }).inputValue(), 'Cliente <Teste> & Cia');
    await page.getByRole('button', { name: 'Limpar proposta', exact: true }).click();
    await page.getByRole('button', { name: 'Sim, limpar', exact: true }).click();
    assert.equal(await page.getByLabel('Cliente', { exact: true }).inputValue(), '');
    await page.setViewportSize({ width: 320, height: 720 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: 'dist/proposal-preview.png' });
    assert.deepEqual(errors, []);
    console.log('PASS: cálculo, navegação, máscaras, itens, desconto, HTML/PDF, logo, confirmação e reset independente das abas. Sem erros JavaScript.');
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exit(1); });
